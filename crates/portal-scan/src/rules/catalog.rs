pub fn meta(id: &str) -> &'static RuleMeta {
    RULES.iter().find(|r| r.id == id).unwrap_or_else(|| panic!("unknown rule {id}"))
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn rule_ids_are_unique_and_words_are_plain() {
        let mut ids: Vec<_> = RULES.iter().map(|r| r.id).collect();
        ids.sort();
        ids.dedup();
        assert_eq!(ids.len(), RULES.len(), "duplicate rule id");
        for r in RULES {
            assert!(!r.title.is_empty() && !r.why.is_empty() && !r.fix.is_empty(), "{}", r.id);
            assert!(!r.why.to_lowercase().contains("will work"), "{}: never promise it works", r.id);
        }
    }
}
