//! The system clipboard (Mission 03 §4): read what's on it, unless the app
//! that put it there marked it private; write what arrived, marked as ours so
//! it's never sent back; and the change counter that automatic sync watches.
//! Plain text, RTF, HTML and images (as PNG). Files copied in Finder or
//! Explorer are reported as such: they travel as a normal transfer.

pub mod convert;

#[cfg(test)]
mod convert_tests;

#[cfg(target_os = "macos")]
mod macos;
#[cfg(target_os = "macos")]
use macos as imp;

#[cfg(windows)]
mod win;
#[cfg(windows)]
use win as imp;

#[cfg(not(any(target_os = "macos", windows)))]
mod imp {
    pub fn change_count() -> u64 {
        0
    }
    pub fn read() -> super::Read {
        super::Read::Empty
    }
    pub fn read_marked_text() -> Option<String> {
        None
    }
    pub fn write(_: &super::Contents, _: bool) -> std::io::Result<u64> {
        Err(std::io::Error::other("no clipboard support on this system"))
    }
    pub fn formats() -> super::Formats {
        super::Formats::default()
    }
}

/// What can travel: each representation the clipboard had.
#[derive(Clone, Debug, Default, PartialEq, Eq)]
pub struct Contents {
    pub text: Option<String>,
    /// Rich text as RTF (both systems use it natively).
    pub rtf: Option<Vec<u8>>,
    /// Rich text as an HTML fragment (browsers put this, not RTF).
    pub html: Option<String>,
    pub png: Option<Vec<u8>>,
}

impl Contents {
    pub fn is_empty(&self) -> bool {
        self.text.as_deref().is_none_or(str::is_empty)
            && self.rtf.is_none()
            && self.html.is_none()
            && self.png.is_none()
    }
}

#[derive(Clone, Debug, PartialEq, Eq)]
pub enum Read {
    /// Nothing that travels (empty, or formats we don't carry).
    Empty,
    /// Another app is holding the clipboard right now (Windows lets one app
    /// at a time open it): try again in a moment (Mission 05 §1.9).
    Busy,
    /// Files copied in Finder or Explorer: they go as a transfer.
    Files(Vec<std::path::PathBuf>),
    /// Marked private by the app that put it there (a password manager, a
    /// private browser window): not read at all. `marker` is the type or
    /// format that said so (its name only); `source`, the app that copied
    /// it, when the system says (a bundle id on macOS, an .exe name on
    /// Windows).
    Private { marker: String, source: Option<String> },
    /// `ours`: SeamDrop put it there (it arrived from the other computer).
    Contents { contents: Contents, ours: bool },
}

/// macOS pasteboard types that mean "don't record or sync this", from the
/// nspasteboard.org convention (the universal ones and the older ones it
/// asks tools to respect). Verified against http://nspasteboard.org.
pub const MAC_PRIVATE_TYPES: &[&str] = &[
    "org.nspasteboard.ConcealedType",
    "org.nspasteboard.TransientType",
    "org.nspasteboard.AutoGeneratedType",
    "de.petermaurer.TransientPasteboardType",
    "com.typeit4me.clipping",
    "Pasteboard generator type",
    "com.agilebits.onepassword",
];

/// Windows clipboard formats that mean "don't monitor or sync this"
/// (Microsoft, "Cloud Clipboard and Clipboard History Formats"): present at
/// all, or a DWORD 0 for the two "Can…" formats. "Clipboard Viewer Ignore"
/// is the older convention KeePass and others still set.
pub const WINDOWS_PRIVATE_FORMATS: &[&str] =
    &["ExcludeClipboardContentFromMonitorProcessing", "Clipboard Viewer Ignore"];
pub const WINDOWS_OPT_OUT_FORMATS: &[&str] = &["CanIncludeInClipboardHistory", "CanUploadToCloudClipboard"];

/// macOS: the bundle id of the app that wrote the pasteboard, by the same
/// nspasteboard.org convention (when the app sets it).
pub const MAC_SOURCE_TYPE: &str = "org.nspasteboard.source";

/// Our own marker on what we write.
pub const MAC_OURS: &str = "com.seamdrop.desktop.received";
pub const WINDOWS_OURS: &str = "SeamDropReceived";

/// Goes up by one (or more) every time anything changes the clipboard.
pub fn change_count() -> u64 {
    imp::change_count()
}

/// Reads the clipboard. If it changes while being read, reads again (so the
/// private check and the contents always belong to the same copy).
pub fn read() -> Read {
    let mut last = Read::Empty;
    for _ in 0..3 {
        let before = imp::change_count();
        last = imp::read();
        if imp::change_count() == before {
            return last;
        }
    }
    last
}

/// What's on the clipboard, by name only (never the content): every format
/// or type, with the DWORD value of Windows' two "Can…" formats, and the app
/// that put it there when the system says. For finding out which markers
/// apps set (`examples/clip_formats.rs`, Mission 04 §4.3).
#[derive(Clone, Debug, Default, PartialEq, Eq)]
pub struct Formats {
    pub names: Vec<String>,
    pub can_include_in_history: Option<u32>,
    pub can_upload_to_cloud: Option<u32>,
    pub source: Option<String>,
}

pub fn formats() -> Formats {
    imp::formats()
}

/// The text on the clipboard *even if an app marked it private*, and the
/// change count it was read at. Only for "Put on Shelf" on a private copy,
/// when the person clicks it (Mission 05 §3.1, amending decision 146):
/// nothing else ever reads marked content.
pub fn read_marked_text() -> Option<(String, u64)> {
    let before = imp::change_count();
    let text = imp::read_marked_text()?;
    (imp::change_count() == before).then_some((text, before))
}

/// Replaces the clipboard with `contents`, marked as ours. Returns the change
/// count right after, so automatic sync can tell its own write apart.
pub fn write(contents: &Contents) -> std::io::Result<u64> {
    imp::write(contents, false)
}

/// The same, marked private the way password managers mark what they copy:
/// clipboard managers, clipboard history and cloud clipboard leave it alone
/// (macOS: nspasteboard.org's concealed and transient types; Windows: the
/// formats in Microsoft's "Cloud Clipboard and Clipboard History Formats").
/// SeamDrop itself then reads it as private too, so it's never sent on.
pub fn write_private(contents: &Contents) -> std::io::Result<u64> {
    imp::write(contents, true)
}
