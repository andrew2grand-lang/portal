// Generates src-tauri/tests/contract.rs from the commands in
// src-tauri/src/bridge.rs: for each command, the argument names (camelCase,
// as Tauri reads them) and the types it declares. The test puts every invoke
// the window sends (tests/fixtures/ui-invokes.json, recorded by
// src/core/contract.test.ts) through those types, with Tauri's rule for a
// missing key (only an Option may be missing).
//
//   node scripts/contract.mjs          write the test
//   node scripts/contract.mjs --check  exit 1 if it's out of date (check:bridge runs this)
import { readFileSync, writeFileSync } from 'node:fs'

const OUT = 'src-tauri/tests/contract.rs'
const rs = readFileSync('src-tauri/src/bridge.rs', 'utf8')

// The module's own imports, so the declared types resolve as they do there
const uses = [...rs.matchAll(/^use [^;]+;/gms)]
  .map((m) => m[0].replace(/\s+/g, ' ').replace(/\bcrate::/g, 'portal_app_lib::'))
  .filter((u) => !/\b(Mutex|VecDeque|mpsc|Emitter|AppHandle|State)\b/.test(u) || /portal_core/.test(u))

const camel = (s) => s.replace(/_([a-z])/g, (_, c) => c.toUpperCase())
const injected = /^(tauri::)?(State|AppHandle|Window|WebviewWindow|Webview)\b/

const commands = []
for (const m of rs.matchAll(/#\[tauri::command\][^\n]*\n(?:\s*#\[[^\n]*\n)*\s*pub (?:async )?fn (portal_\w+)\s*(?:<[^>]*>)?\(([^)]*)\)/g)) {
  const [, name, raw] = m
  // Drop State<'_, Bridge> first: its comma isn't an argument separator
  const params = raw
    .replace(/\w+\s*:\s*(tauri::)?State<[^>]*>/g, '')
    .split(',')
    .map((p) => p.trim())
    .filter(Boolean)
    .map((p) => {
      const i = p.indexOf(':')
      return { name: p.slice(0, i).trim(), type: p.slice(i + 1).trim() }
    })
    .filter((p) => !injected.test(p.type))
  commands.push({ name, params })
}
if (commands.length < 10) throw new Error(`only found ${commands.length} commands in bridge.rs`)

const arms = commands
  .map(({ name, params }) => {
    const checks = params.map((p) => `arg::<${p.type}>(cmd, args, "${camel(p.name)}")?;`).join(' ')
    return `        "${name}" => { ${checks} }`
  })
  .join('\n')

const out = `//! Generated by \`node scripts/contract.mjs\` from src-tauri/src/bridge.rs: don't edit.
//!
//! The UI ↔ Rust contract: every invoke the window sends
//! (\`fixtures/ui-invokes.json\`, recorded by src/core/contract.test.ts) goes
//! through the argument types its command declares, as Tauri reads them: a
//! present key with serde, a missing key only for an \`Option\`. beta.1 shipped
//! with every partial Settings patch refused this way.
#![allow(unused_imports)]
${uses.join('\n')}
use portal_app_lib::bridge::*;
use serde_json::Value;

fn arg<T: serde::de::DeserializeOwned>(cmd: &str, args: &Value, key: &str) -> Result<(), String> {
    let value = args.get(key).cloned().unwrap_or(Value::Null);
    serde_json::from_value::<T>(value).map(|_| ()).map_err(|e| format!("{cmd}: \`{key}\` {e} (sent: {args})"))
}

fn check(cmd: &str, args: &Value) -> Result<(), String> {
    match cmd {
${arms}
        _ => return Err(format!("{cmd} isn't a command in bridge.rs")),
    }
    Ok(())
}

const COMMANDS: &[&str] = &[${commands.map((c) => `"${c.name}"`).join(', ')}];

fn calls() -> Vec<(String, Value)> {
    let raw: Vec<Value> = serde_json::from_str(include_str!("fixtures/ui-invokes.json")).expect("the fixture");
    raw.into_iter().map(|c| (c["cmd"].as_str().unwrap_or_default().to_owned(), c["args"].clone())).collect()
}

#[test]
fn every_invoke_the_window_sends_is_accepted() {
    let failures: Vec<String> = calls().iter().filter_map(|(cmd, args)| check(cmd, args).err()).collect();
    assert!(failures.is_empty(), "refused by Rust:\\n{}", failures.join("\\n"));
}

#[test]
fn every_command_is_sent_by_the_window_at_least_once() {
    let sent: Vec<String> = calls().into_iter().map(|(c, _)| c).collect();
    let missing: Vec<&&str> = COMMANDS.iter().filter(|c| !sent.iter().any(|s| s == **c)).collect();
    assert!(missing.is_empty(), "never exercised: {missing:?}");
}
`

if (process.argv.includes('--check')) {
  let now = ''
  try {
    now = readFileSync(OUT, 'utf8')
  } catch {
    // missing: out of date
  }
  if (now !== out) {
    console.error(`✗ ${OUT} is out of date: run node scripts/contract.mjs`)
    process.exit(1)
  }
  console.log(`✓ ${OUT} matches bridge.rs (${commands.length} commands)`)
} else {
  writeFileSync(OUT, out)
  console.log(`wrote ${OUT} (${commands.length} commands)`)
}
